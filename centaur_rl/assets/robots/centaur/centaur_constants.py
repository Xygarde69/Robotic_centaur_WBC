"""Centaur constants (legs only; upper body currently removed from the training MJCF).

The MJCF is generated by `mjcf/build_train_xml.py` from `mjcf/centaur.xml`.

Frame: +x forward (torso end), +y left, z up. FR/RR are on the right (y < 0).
Joints: <leg>_1 = hip ab/ad, <leg>_2 = thigh (hip pitch), <leg>_3 = calf (knee).
Because the CAD axes are mirrored, pitch joints on the left (FL/RL) and right (FR/RR)
have opposite signs for the same physical motion.
Collision: only the calf meshes (<leg>_calf_collision) collide; they act as the feet.
"""

from pathlib import Path

import mujoco

from centaur_rl import REPO_ROOT
from mjlab.actuator import BuiltinPositionActuatorCfg
from mjlab.entity import EntityArticulationInfoCfg, EntityCfg
from mjlab.utils.os import update_assets
from mjlab.utils.spec_config import CollisionCfg

##
# MJCF and assets.
##

CENTAUR_XML: Path = REPO_ROOT / "mjcf" / "centaur_train.xml"
assert CENTAUR_XML.exists(), f"{CENTAUR_XML} missing: run `python mjcf/build_train_xml.py`"

LEG_NAMES = ("FR", "FL", "RR", "RL")


def get_assets(meshdir: str) -> dict[str, bytes]:
  assets: dict[str, bytes] = {}
  update_assets(assets, CENTAUR_XML.parent / "meshes", meshdir)
  return assets


def get_spec() -> mujoco.MjSpec:
  spec = mujoco.MjSpec.from_file(str(CENTAUR_XML))
  spec.assets = get_assets(spec.meshdir)
  return spec


##
# Actuator config.
#
# kp=150 matches the CAD export's position actuators; lower gains sag 0.2-0.3 rad under
# the ~58 kg welded-upper-body robot. Kept for the ~35.5 kg quadruped-only model too.
##

EFFORT_LIMIT = 100.0

CENTAUR_ACTUATOR_HIP = BuiltinPositionActuatorCfg(
  target_names_expr=(r"(FR|FL|RR|RL)_1",),
  stiffness=150.0,
  damping=5.0,
  effort_limit=EFFORT_LIMIT,
  armature=0.02,
)
CENTAUR_ACTUATOR_THIGH = BuiltinPositionActuatorCfg(
  target_names_expr=(r"(FR|FL|RR|RL)_2",),
  stiffness=150.0,
  damping=5.0,
  effort_limit=EFFORT_LIMIT,
  armature=0.02,
)
CENTAUR_ACTUATOR_CALF = BuiltinPositionActuatorCfg(
  target_names_expr=(r"(FR|FL|RR|RL)_3",),
  stiffness=150.0,
  damping=5.0,
  effort_limit=EFFORT_LIMIT,
  armature=0.03,
)

##
# Keyframes.
#
# Knees-back stance (like Go2). FL/RL pitch axes are +y, FR/RR are -y, hence the sign flip.
##

THIGH_ANGLE = 0.45
CALF_ANGLE = -0.9

INIT_STATE = EntityCfg.InitialStateCfg(
  pos=(0.0, 0.0, 0.58),
  joint_pos={
    r".*_1": 0.0,
    r"(FL|RL)_2": THIGH_ANGLE,
    r"(FL|RL)_3": CALF_ANGLE,
    r"(FR|RR)_2": -THIGH_ANGLE,
    r"(FR|RR)_3": -CALF_ANGLE,
  },
  joint_vel={".*": 0.0},
)

##
# Collision config.
##

FOOT_GEOM_NAMES = tuple(f"{leg}_calf_collision" for leg in LEG_NAMES)

# Calf meshes vs. terrain only (no self collisions). Nothing else in the model collides.
CALF_ONLY_COLLISION = CollisionCfg(
  geom_names_expr=(r"^(FR|FL|RR|RL)_calf_collision$",),
  contype=1,
  conaffinity=0,
  condim=3,
  priority=1,
  friction=(0.6,),
  solimp=(0.9, 0.95, 0.023),
)

##
# Final config.
##

CENTAUR_ARTICULATION = EntityArticulationInfoCfg(
  actuators=(
    CENTAUR_ACTUATOR_HIP,
    CENTAUR_ACTUATOR_THIGH,
    CENTAUR_ACTUATOR_CALF,
  ),
  soft_joint_pos_limit_factor=0.9,
)


def get_centaur_robot_cfg() -> EntityCfg:
  """Get a fresh Centaur robot configuration instance."""
  return EntityCfg(
    init_state=INIT_STATE,
    collisions=(CALF_ONLY_COLLISION,),
    spec_fn=get_spec,
    articulation=CENTAUR_ARTICULATION,
  )


if __name__ == "__main__":
  import mujoco.viewer as viewer

  from mjlab.entity.entity import Entity

  robot = Entity(get_centaur_robot_cfg())
  viewer.launch(robot.spec.compile())
